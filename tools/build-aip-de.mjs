/* Builds functions/_lib/aip-de.js: Germany's aerodromes → DFS permalinks (https://aip.dfs.de/Basic{IFR,VFR}/pages/<C…>.html).
   DFS names its pages by hash, new for every edition, but each page also has a permalink that always redirects to the
   edition in force. So this map only changes when an aerodrome is added or removed; the weekly AIP workflow re-runs this
   script and commits the file when it changed.   node tools/build-aip-de.mjs */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const UA = 'Mozilla/5.0 (compatible; NORDAP/1.0; +https://nordap.eu)';
const get = async u => { for (let i = 0; i < 3; i++) { try { const r = await fetch(u, { headers: { 'user-agent': UA }, signal: AbortSignal.timeout(60000) }); if (r.ok) return { url: r.url, t: await r.text() }; } catch (e) {} await new Promise(r => setTimeout(r, 1500)); } throw new Error('failed ' + u); };
const anchors = t => [...t.matchAll(/<a\b[^>]*href\s*=\s*["']([0-9a-f]{32}\.html)["'][^>]*>([\s\S]{0,300}?)<\/a>/gi)].map(m => [m[1], m[2].replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim()]).filter(a => /raquo|»/.test(a[1]));
const perm = t => (t.match(/myPermalink = "pages\/(C[0-9A-F]+)\.html"/) || [])[1];
function owner(t) {   // the aerodrome a page is about: the ICAO code it names far more often than any other
  const b = t.slice(t.indexOf('<body')); const cnt = {};
  for (const c of (b.match(/\bE[DT][A-Z]{2}\b/g) || []).slice(0, 5000)) cnt[c] = (cnt[c] || 0) + 1;
  const s = Object.entries(cnt).sort((x, y) => y[1] - x[1]);
  return s.length && s[0][1] >= 3 && (!s[1] || s[0][1] >= 3 * s[1][1]) ? s[0][0] : null;
}
async function crawl(kind, pick) {
  const root = await get(`https://aip.dfs.de/${kind}/`); const base = root.url.replace(/[^/]*$/, '');
  const ad = anchors(root.t).find(a => /^AD\b/.test(a[1])); if (!ad) throw new Error(kind + ': no AD');
  const adp = await get(new URL(ad[0], base).href);
  const groups = anchors(adp.t).filter(a => pick(a[1]));
  const out = {}; let n = 0;
  async function leafOrGroup(href, depth) {
    const p = await get(new URL(href, base).href); n++;
    const kids = anchors(p.t);
    const own = owner(p.t), c = perm(p.t);
    if (own && c && (!kids.length || depth >= 1)) { if (!out[own]) out[own] = c; return; }
    if (depth < 2) for (const k of kids) await leafOrGroup(k[0], depth + 1);
  }
  for (const g of groups) await leafOrGroup(g[0], 0);
  console.log(kind, Object.keys(out).length, 'aerodromes,', n, 'pages,', 'edition', base.match(/\/(\d{4}[A-Z]{3}\d{2})\//)?.[1]);
  return out;
}
const ifr = await crawl('BasicIFR', t => /^(MIL-)?AD 2\b/.test(t));
const vfr = await crawl('BasicVFR', t => /^[A-Z](-[A-Z])?\s/.test(t) && !/^AD\b/.test(t));
if (Object.keys(ifr).length < 40) throw new Error('IFR list looks incomplete');
const sort = o => Object.fromEntries(Object.entries(o).sort());
const body = `/* Generated by tools/build-aip-de.mjs – do not edit. Germany: aerodrome → DFS permalink (redirects to the edition in force). */
export default ${JSON.stringify({ ifr: sort(ifr), vfr: sort(vfr) })};
`;
writeFileSync(join(ROOT, 'functions/_lib/aip-de.js'), body);
console.log('written: IFR', Object.keys(ifr).length, 'VFR', Object.keys(vfr).length);
